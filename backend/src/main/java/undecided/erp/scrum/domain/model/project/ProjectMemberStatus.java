package undecided.erp.scrum.domain.model.project;

/**
 * プロジェクトメンバーの状態を表す列挙型です。
 *
 * <p>このクラスは以下の状態を定義します:
 *
 * <ul>
 *   <li>INVITED: 招待中のメンバー。招待が送信されたが、まだ承諾または拒否されていない状態。
 *   <li>ACTIVE: アクティブなメンバー。招待を承諾し、プロジェクトに参加している状態。
 *   <li>DECLINED: 招待を拒否したメンバー。招待を拒否した状態。
 *   <li>REMOVED: プロジェクトから削除されたメンバー。以前はプロジェクトに参加していたが、現在は削除された状態。
 * </ul>
 */
public enum ProjectMemberStatus {
  /**
   * 招待中のメンバー。
   *
   * <p>招待が送信されたが、まだ承諾または拒否されていない状態を表します。
   */
  INVITED,

  /**
   * アクティブなメンバー。
   *
   * <p>招待を承諾し、プロジェクトに参加している状態を表します。
   */
  ACTIVE,

  /**
   * 招待を拒否したメンバー。
   *
   * <p>招待を拒否した状態を表します。
   */
  DECLINED,

  /**
   * プロジェクトから削除されたメンバー。
   *
   * <p>以前はプロジェクトに参加していたが、現在は削除された状態を表します。
   */
  REMOVED
}
